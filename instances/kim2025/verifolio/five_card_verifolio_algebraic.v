(******************************************************************************)
(*     The algebra as the first line of a program                             *)
(******************************************************************************)

(** The five-card instance at the Algebraic level: the algebra alone, under
    True, the proposition that level carries. One run mode is built on this
    value, the committed one: the Executable file continues it into
    five_card_committed_executable, and five_card_committed_executableE
    identifies that value, with the three run facts adjoined, with the
    prefix all seven published programs continue from. *)
Definition five_card_algebraic_start : Verifolio Algebraic :=
  verifolio_start five_card_algebra.


(******************************************************************************)
(*     The ideal function the run computes                                    *)
(******************************************************************************)

(** The algebra together with the ideal function a run of it computes. A
    dealer-dealt run has the identity forced on it and writes no such
    record; a run whose input is committed by two parties does not, and the
    function has to be named. The prefix five_card_committed names the same
    one in its own functionality clause, and the two spellings are held
    together by five_card_realises_expected, which is reflexivity only while
    they agree. *)
Definition five_card_target : Targeted :=
  five_card_algebra functionality (fun ab : bool * bool => ab.1 && ab.2).

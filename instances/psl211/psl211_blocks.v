(* The image of a row under a letter table, sorted. *)
Definition psl211_map_row (g : seq nat) (R : seq nat) : seq nat :=
  sort leq [seq nth 0 g x | x <- R].

(** psl211_stable_ok g tbl — g maps every row of tbl to a row of tbl. *)
Definition psl211_stable_ok (g : seq nat) (tbl : seq (seq nat)) : bool :=
  all (fun R => psl211_map_row g R \in tbl) tbl.


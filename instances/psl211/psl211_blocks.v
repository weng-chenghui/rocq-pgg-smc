(* Ascending code lists of size k with entries in [lo, 12). *)
Fixpoint psl211_asc_lists (k lo : nat) : seq (seq nat) :=
  match k with
  | 0 => [:: [::]]
  | k'.+1 =>
    flatten [seq [seq a :: L | L <- psl211_asc_lists k' a.+1]
            | a <- iota lo (12 - lo)]
  end.

(** psl211_subsets k — every ascending k-list of codes below twelve. *)
Definition psl211_subsets (k : nat) : seq (seq nat) := psl211_asc_lists k 0.

(** psl211_size_subsets5 — there are exactly 792 ascending five-lists of
    codes below twelve. *)
Lemma psl211_size_subsets5 : size (psl211_subsets 5) = 792.
Proof. by vm_compute. Qed.

(* Sublist test on sorted lists. *)
Definition psl211_subl (S R : seq nat) : bool := all (fun x => x \in R) S.

(** psl211_design5_ok tbl — every five-list lies in exactly one row of tbl. *)
Definition psl211_design5_ok (tbl : seq (seq nat)) : bool :=
  all (fun S => count (fun R => psl211_subl S R) tbl == 1) (psl211_subsets 5).

(** psl211_design5_mirrorT — psl211_mirror_tbl is a 5-(12,6,1) design: every
    five-subset of the twelve positions lies in exactly one block. *)
Lemma psl211_design5_mirrorT : psl211_design5_ok psl211_mirror_tbl.
Proof. by vm_compute. Qed.
(** psl211_design5_hexadT — psl211_hexad_tbl is a 5-(12,6,1) design: every

(* psl211_blocks: the literal data of the twelve-card chirality instance      *)
(*                                                                            *)
(* Twelve positions 0..11. Three letter tables: reverse each quarter (r4),    *)
(* Monge-shuffle each half (m6) and its inverse, milk-shuffle each half.     *)
(* Two 132-row tables of ascending six-lists: the two Steiner systems         *)
(* S(5,6,12) on the twelve positions, the hexad system of M12 and its mirror. *)
(* A sixth table transports the non-square scaling of P^1(F_11) to this      *)
(* labelling; it exchanges the two systems and lies outside the group.       *)
(*                                                                            *)
(* Every certificate below is a vm_compute on these tables:                   *)
(*   psl211_design5_mirrorT/_hexadT == each table is a 5-(12,6,1) design     *)
(*   psl211_stable_*T               == r4 and m6 map each table into itself   *)
(*   psl211_count_okT               == equal pattern counts, coalitions <= 5  *)
(*   psl211_leak6                   == a size-6 pattern with unequal counts   *)
(*   psl211_chirality_swapT         == the transported scaling swaps the two  *)
(******************************************************************************)


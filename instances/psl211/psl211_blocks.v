(** psl211_chirality_swapT — the transported non-square scaling carries every
    mirror row to a hexad row and every hexad row to a mirror row: the
    PGL(2,11) letter that PSL(2,11) lacks exchanges the two secret classes. *)
Lemma psl211_chirality_swapT :
  psl211_stable_ok psl211_nonsquare_tbl psl211_mirror_tbl = false /\
  all (fun R => psl211_map_row psl211_nonsquare_tbl R \in psl211_hexad_tbl)
      psl211_mirror_tbl /\
  all (fun R => psl211_map_row psl211_nonsquare_tbl R \in psl211_mirror_tbl)
      psl211_hexad_tbl.
Proof. by vm_compute. Qed.

(* Intersection of a sorted row with a coalition list. *)
Definition psl211_inter (R C : seq nat) : seq nat := [seq x <- R | x \in C].

(** psl211_pattern_count tbl C A — rows of tbl meeting C in exactly A. *)
Definition psl211_pattern_count (tbl : seq (seq nat)) (C A : seq nat) : nat :=
  count (fun R => psl211_inter R C == A) tbl.

(* Every ascending sublist of an ascending list. *)
Fixpoint psl211_sublists (C : seq nat) : seq (seq nat) :=
  match C with
  | [::] => [:: [::]]
  | a :: C' => let S := psl211_sublists C' in S ++ [seq a :: L | L <- S]
  end.

(** psl211_count_ok_k k — for every coalition of exactly k positions and
    every pattern on it, psl211_mirror_tbl and psl211_hexad_tbl show the
    pattern equally often. *)
Definition psl211_count_ok_k (k : nat) : bool :=
  all (fun C => all (fun A =>
         psl211_pattern_count psl211_mirror_tbl C A
         == psl211_pattern_count psl211_hexad_tbl C A) (psl211_sublists C))
      (psl211_subsets k).

(** psl211_count_ok — for every coalition of at most five positions and every
    pattern, the two systems have the same number of blocks showing it. *)
Definition psl211_count_ok : bool :=
  [&& psl211_count_ok_k 1, psl211_count_ok_k 2, psl211_count_ok_k 3,
      psl211_count_ok_k 4 & psl211_count_ok_k 5].

(* 38.7 s measured (PROBE-REPORT.md). *)
Lemma psl211_count_okT : psl211_count_ok.
Proof. by vm_compute. Qed.

(** psl211_leak6 — the mirror representative row [2;3;5;7;8;9], taken as a
    six-coalition seeing all hearts, is shown by one mirror block and by no
    hexad block. The same witness the distributional leak of
    psl211_secrecy.v (psl211_leak_coalition) uses. *)
Lemma psl211_leak6 :
  psl211_pattern_count psl211_mirror_tbl [:: 2; 3; 5; 7; 8; 9] [:: 2; 3; 5; 7; 8; 9] = 1 /\
  psl211_pattern_count psl211_hexad_tbl [:: 2; 3; 5; 7; 8; 9] [:: 2; 3; 5; 7; 8; 9] = 0.
Proof. by vm_compute. Qed.

(* -------------------------------------------------------------------------- *)
(* The five symmetrized generators and their permutation tables of 'I_8.      *)
(* -------------------------------------------------------------------------- *)

(** pgl27_sym_sigmas — the inverse-closed symmetrized generator tuple of the
    realistic word shuffle: translation, scaling, inversion and the two
    inverses of translation and scaling. The letter alphabet of the L-word
    shuffle. *)
Definition pgl27_sym_sigmas : 5.-tuple {perm 'I_8} :=
  [tuple tnth pgl27_gens (@Ordinal 3 0 isT);
         ((tnth pgl27_gens (@Ordinal 3 0 isT))^-1)%g;
         tnth pgl27_gens (@Ordinal 3 1 isT);
         ((tnth pgl27_gens (@Ordinal 3 1 isT))^-1)%g;
         tnth pgl27_gens (@Ordinal 3 2 isT)].

(* The permutation table of the j-th letter, read off by position. *)
Local Definition mtbl (j : nat) : seq nat :=
  nth [::] [:: [:: 1; 2; 3; 4; 5; 6; 0; 7]
             ; [:: 6; 0; 1; 2; 3; 4; 5; 7]
             ; [:: 0; 3; 6; 2; 5; 1; 4; 7]
             ; [:: 0; 5; 3; 1; 6; 4; 2; 7]
             ; [:: 7; 6; 3; 2; 5; 4; 1; 0]] j.

(* A permutation whose forward images are read off the table F has (g^-1) x
   at Finv, whenever Finv is a right inverse of F on the eight codes.  The two
   inverse letters of the symmetrized alphabet are given by tables this way,
   so no permutation is ever inverted inside a kernel computation. *)
Local Lemma perm_inv_val (g : {perm 'I_8}) (F Finv : seq nat) (x : 'I_8) :
  (forall y : 'I_8, val (g y) = nth 0 F (val y)) ->
  (forall k, k < 8 -> nth 0 F (nth 0 Finv k) = k) ->
  (forall k, k < 8 -> nth 0 Finv k < 8) ->
  val ((g^-1)%g x) = nth 0 Finv (val x).
Proof.
move=> Hfwd Hcomp Hrange.
have Hc8 : nth 0 Finv (val x) < 8 by apply: Hrange; exact: ltn_ord.
pose z : 'I_8 := Ordinal Hc8.
have Hgz : g z = x.
  by apply/val_inj; rewrite Hfwd /= Hcomp //; exact: ltn_ord.
have Hzx : (g^-1)%g x = z by rewrite -Hgz permK.
by rewrite Hzx.
Qed.

(* The three forward generators agree with their nat-level tables. *)
Local Lemma gfwd0 (x : 'I_8) :
  val (tnth pgl27_gens (@Ordinal 3 0 isT) x) = nth 0 (mtbl 0) (val x).
Proof. by case: x => -[|[|[|[|[|[|[|[|//]]]]]]]] Hx; rewrite permE. Qed.
Local Lemma gfwd1 (x : 'I_8) :
  val (tnth pgl27_gens (@Ordinal 3 1 isT) x) = nth 0 (mtbl 2) (val x).
Proof. by case: x => -[|[|[|[|[|[|[|[|//]]]]]]]] Hx; rewrite permE. Qed.
Local Lemma gfwd2 (x : 'I_8) :
  val (tnth pgl27_gens (@Ordinal 3 2 isT) x) = nth 0 (mtbl 4) (val x).
Proof. by case: x => -[|[|[|[|[|[|[|[|//]]]]]]]] Hx; rewrite permE. Qed.

(* Each of the five letters sends a code to the entry of its own table at that
   code.  The alphabet is therefore described entirely by mtbl, which is the
   form the BFS closure and the walk recursion compute in. *)
Local Lemma mtbl_val (j : 'I_5) (x : 'I_8) :
  val (tnth pgl27_sym_sigmas j x) = nth 0 (mtbl j) (val x).
Proof.
case: j => -[|[|[|[|[|//]]]]] Hj; rewrite (tnth_nth 1%g) /=.
- exact: gfwd0.
- apply: (perm_inv_val (F := mtbl 0)); first exact: gfwd0.
  + by case=> [|[|[|[|[|[|[|[|k7]]]]]]]].
  + by case=> [|[|[|[|[|[|[|[|k7]]]]]]]].
- exact: gfwd1.
- apply: (perm_inv_val (F := mtbl 2)); first exact: gfwd1.
  + by case=> [|[|[|[|[|[|[|[|k7]]]]]]]].
  + by case=> [|[|[|[|[|[|[|[|k7]]]]]]]].
- exact: gfwd2.
Qed.

(* -------------------------------------------------------------------------- *)
(* Nat-level breadth-first enumeration of the group as permutation tables.    *)
(* -------------------------------------------------------------------------- *)

(* Composition of two tables: the table of the second read at the first. *)
Local Definition mcomp (t1 t2 : seq nat) : seq nat :=
  map (fun x => nth 0 t2 x) t1.
Local Definition idt : seq nat := [:: 0; 1; 2; 3; 4; 5; 6; 7].

(* Fueled search keeping, for each reached table, a carrying letter word. *)
Local Fixpoint elem_bfs (fuel : nat) (seen : seq (seq nat * seq nat)) :
    seq (seq nat * seq nat) :=
  match fuel with
  | 0 => seen
  | S f =>
    let nxt := flatten
      [seq [seq (mcomp tw.1 (mtbl j), rcons tw.2 j) | j <- [:: 0; 1; 2; 3; 4]]
      | tw <- seen] in
    let add := foldl (fun acc tw =>
      if has (fun sw : seq nat * seq nat => sw.1 == tw.1) (seen ++ acc)
      then acc else rcons acc tw) [::] nxt in
    if size add == 0 then seen else elem_bfs f (seen ++ add)
  end.

(* Reached tables paired with a carrying word, from the identity table. *)
Local Definition elem_table : seq (seq nat * seq nat) :=
  elem_bfs 12 [:: (idt, [::])].

(* The position of a table among the reached keys. *)
Local Definition tbl_index (t : seq nat) : nat :=
  find (fun sw : seq nat * seq nat => sw.1 == t) elem_table.

(* The letter carrying a state back along the reverse walk. *)
Local Definition inv_letter (j : nat) : nat := nth 0 [:: 1; 0; 3; 2; 4] j.

(* For each key, the indices of its five reverse-walk predecessors. *)
Local Definition pred_table : seq (seq nat) :=
  [seq [seq tbl_index (mcomp sw.1 (mtbl (inv_letter j)))
       | j <- [:: 0; 1; 2; 3; 4]]
  | sw <- elem_table].

(* The closure has 336 uniq keys, opens at the identity, every word folds to
   its key, every one-letter successor stays in the list, and every word
   carries only letters below five. *)
Local Definition elem_table_ok : bool :=
  [&& size elem_table == 336,
      uniq (unzip1 elem_table),
      nth ([::], [::]) elem_table 0 == (idt, [::]),
      all (fun sw : seq nat * seq nat =>
             foldl (fun t j => mcomp t (mtbl j)) idt sw.2 == sw.1)
          elem_table,
      all (fun sw : seq nat * seq nat =>
             all (fun j => nth [::] (unzip1 elem_table)
                     (tbl_index (mcomp sw.1 (mtbl j))) == mcomp sw.1 (mtbl j))
                 [:: 0; 1; 2; 3; 4])
          elem_table
    & all (fun sw : seq nat * seq nat =>
             all (fun j => j < 5) sw.2) elem_table].
(* Every conjunct of elem_table_ok holds.  This single kernel computation is
   what the group order and the walk's 336-state indexing both rest on: it
   fixes the number of states, their uniqueness, the state of the identity,
   and closure of the state set under the five letters. *)
Local Lemma elem_table_okT : elem_table_ok.
Proof. by vm_compute. Qed.

(* -------------------------------------------------------------------------- *)
(* The binary-N random walk of length L over the 336 states.                  *)
(* -------------------------------------------------------------------------- *)

(* walkN L s counts the length-L letter words carrying the identity to s. *)
Local Fixpoint walkN (L : nat) : seq N :=
  match L with
  | 0 => 1%num :: nseq 335 0%num
  | L'.+1 =>
    let v := walkN L' in
    [seq foldl (fun acc i => (acc + nth 0%num v i)%num) 0%num preds
    | preds <- pred_table]
  end.

(* Absolute difference of two binary naturals. *)
Local Definition absdiffN (a b : N) : N :=
  if (a <? b)%num then (b - a)%num else (a - b)%num.

(* The integer form of the mixing bound: 2^40 times the total absolute
   deviation of the 336 walk counts from the uniform value 5^200 / 336, taken
   over the common denominator, is at most 336 * 5^200. *)
Local Definition mixing_bound_ok : bool :=
  let D := (5 ^ 200)%num in
  ((2 ^ 40) * foldl (fun acc c => (acc + absdiffN (336 * c) D)%num) 0%num
                    (walkN 200)
   <=? 336 * D)%num.
(* The length-200 walk meets that integer bound.  It is the only quantitative
   input to the mixing theorem; everything after it is exact rewriting. *)
Local Lemma mixing_bound_okT : mixing_bound_ok.
Proof. by vm_compute. Qed.

(* -------------------------------------------------------------------------- *)
(* Small facts read off the closure checker: the six conjuncts of             *)
(* elem_table_ok, each projected out for use on its own.                      *)
(* -------------------------------------------------------------------------- *)

Local Lemma size_elem_table : size elem_table = 336.
Proof. by move: elem_table_okT => /andP[/eqP H _]. Qed.
Local Lemma uniq_elem_keys : uniq (unzip1 elem_table).
Proof. by move: elem_table_okT => /andP[_ /andP[H _]]. Qed.
Local Lemma elem_table0 : nth ([::], [::]) elem_table 0 = (idt, [::]).
Proof. by move: elem_table_okT => /andP[_ /andP[_ /andP[/eqP H _]]]. Qed.
Local Lemma elem_fold_key (sw : seq nat * seq nat) :
  sw \in elem_table -> foldl (fun t j => mcomp t (mtbl j)) idt sw.2 = sw.1.
Proof.
move=> Hsw; apply/eqP.
by move: elem_table_okT => /andP[_ /andP[_ /andP[_ /andP[/allP/(_ _ Hsw) H _]]]].
Qed.
Local Lemma elem_closed (sw : seq nat * seq nat) :
  sw \in elem_table ->
  all (fun j => nth [::] (unzip1 elem_table)
          (tbl_index (mcomp sw.1 (mtbl j))) == mcomp sw.1 (mtbl j)) [:: 0;1;2;3;4].
Proof.
move=> Hsw.
by move: elem_table_okT =>
  /andP[_ /andP[_ /andP[_ /andP[_ /andP[/allP/(_ _ Hsw) H _]]]]].
Qed.
Local Lemma elem_letters (sw : seq nat * seq nat) :
  sw \in elem_table -> all (fun j => j < 5) sw.2.
Proof.
move=> Hsw.
by move: elem_table_okT =>
  /andP[_ /andP[_ /andP[_ /andP[_ /andP[_ /allP/(_ _ Hsw) H]]]]].
Qed.

(* Tables composed by [mcomp] and folded keep length eight. *)
Local Lemma size_mcomp (t1 t2 : seq nat) : size (mcomp t1 t2) = size t1.
Proof. by rewrite /mcomp size_map. Qed.
Local Lemma size_fold (w : seq nat) :
  size (foldl (fun t j => mcomp t (mtbl j)) idt w) = 8.
Proof.
have gen : forall (w' : seq nat) (t : seq nat), size t = 8 ->
    size (foldl (fun t0 j => mcomp t0 (mtbl j)) t w') = 8.
  by elim=> [|j w' IH] t Ht //=; apply: IH; rewrite size_mcomp.
by apply: gen.
Qed.
(* Every closure key is a table of the eight codes. *)
Local Lemma elem_key_size (sw : seq nat * seq nat) :
  sw \in elem_table -> size sw.1 = 8.
Proof. by move=> Hsw; rewrite -(elem_fold_key Hsw) size_fold. Qed.

(* Every one-letter successor of a key is itself a key. *)
Local Lemma elem_closed_mem (sw : seq nat * seq nat) (j : nat) :
  sw \in elem_table -> j \in [:: 0; 1; 2; 3; 4] ->
  mcomp sw.1 (mtbl j) \in unzip1 elem_table.
Proof.
move=> Hsw Hj.
have /eqP Heq := allP (elem_closed Hsw) j Hj.
have Hsz8 : size (mcomp sw.1 (mtbl j)) = 8 by rewrite size_mcomp (elem_key_size Hsw).
rewrite -Heq; apply: mem_nth.
rewrite ltnNge; apply/negP => Hge.
move: Heq; rewrite (nth_default _ Hge) => Habs.
by move: Hsz8; rewrite -Habs.
Qed.
(* The identity table is a key, and by elem_table0 it is the key at index 0,
   so state 0 of the walk is the identity shuffle. *)
Local Lemma idt_in_keys : idt \in unzip1 elem_table.
Proof.
have -> : idt = nth [::] (unzip1 elem_table) 0.
  rewrite (nth_map ([::], [::])); last by rewrite size_elem_table.
  by rewrite elem_table0.
by apply: mem_nth; rewrite size_map size_elem_table.
Qed.

(* -------------------------------------------------------------------------- *)
(* The permutation-table map and its group structure.                         *)
(* -------------------------------------------------------------------------- *)

(* The table of a permutation of 'I_8: its list of images in code order.
   This is the transport between {perm 'I_8}, where the shuffle group lives,
   and seq nat, where vm_compute reduces. *)
Local Definition ptbl (g : {perm 'I_8}) : seq nat := [seq val (g x) | x <- enum 'I_8].
Local Lemma ptbl_nth (g : {perm 'I_8}) (x : 'I_8) : nth 0 (ptbl g) (val x) = val (g x).
Proof.
rewrite /ptbl (nth_map x) ?size_enum_ord ?ltn_ord //.
by rewrite nth_ord_enum.
Qed.
Local Lemma ptbl_size (g : {perm 'I_8}) : size (ptbl g) = 8.
Proof. by rewrite /ptbl size_map size_enum_ord. Qed.
Local Lemma ptbl_id : ptbl 1%g = idt.
Proof.
apply: (@eq_from_nth _ 0); rewrite ?ptbl_size // => i Hi.
have := ptbl_nth 1%g (Ordinal Hi); rewrite perm1 /= => ->.
by case: i Hi => [|[|[|[|[|[|[|[|k]]]]]]]].
Qed.
Local Lemma size_mtbl (j : nat) : j < 5 -> size (mtbl j) = 8.
Proof. by case: j => [|[|[|[|[|//]]]]]. Qed.
(* A permutation whose images are read off a length-eight list has that list
   as its table. *)
Local Lemma ptbl_of_fwd (g : {perm 'I_8}) (F : seq nat) :
  (forall x, val (g x) = nth 0 F (val x)) -> size F = 8 -> ptbl g = F.
Proof.
move=> Hfwd HF; apply: (@eq_from_nth _ 0); first by rewrite ptbl_size HF.
move=> i; rewrite ptbl_size => Hi.
transitivity (val (g (Ordinal Hi))); first by rewrite -ptbl_nth.
by rewrite Hfwd.
Qed.
(* The tables of the three generators and of the five letters are the mtbl
   entries they were written down as, so the alphabet the BFS closes under is
   the alphabet of the shuffle. *)
Local Lemma ptbl_gen0 : ptbl (tnth pgl27_gens (@Ordinal 3 0 isT)) = mtbl 0.
Proof. by apply: ptbl_of_fwd => //; exact: gfwd0. Qed.
Local Lemma ptbl_gen1 : ptbl (tnth pgl27_gens (@Ordinal 3 1 isT)) = mtbl 2.
Proof. by apply: ptbl_of_fwd => //; exact: gfwd1. Qed.
Local Lemma ptbl_gen2 : ptbl (tnth pgl27_gens (@Ordinal 3 2 isT)) = mtbl 4.
Proof. by apply: ptbl_of_fwd => //; exact: gfwd2. Qed.
Local Lemma ptbl_sym (j : 'I_5) : ptbl (tnth pgl27_sym_sigmas j) = mtbl (val j).
Proof. by apply: ptbl_of_fwd; [exact: mtbl_val | rewrite size_mtbl // ltn_ord]. Qed.
(* ptbl is a morphism: the table of a product is the composition of the two
   tables.  With ptbl_inj this makes ptbl a faithful representation of the
   shuffle group inside seq nat, which is what lets a computation on the 336
   tables settle a question about the group. *)
Local Lemma ptbl_morph (g h : {perm 'I_8}) :
  ptbl (g * h)%g = mcomp (ptbl g) (ptbl h).
Proof.
apply: (@eq_from_nth _ 0); first by rewrite ptbl_size /mcomp size_map ptbl_size.
move=> i; rewrite ptbl_size => Hi.
transitivity (val ((g * h)%g (Ordinal Hi))); first by rewrite -ptbl_nth.
rewrite permM /mcomp (nth_map 0) ?ptbl_size //.
have -> : nth 0 (ptbl g) i = val (g (Ordinal Hi)) by rewrite -ptbl_nth.
by rewrite ptbl_nth.
Qed.
(* Distinct shuffles have distinct tables, so an identity of tables is an
   identity of shuffles. *)
Local Lemma ptbl_inj : injective ptbl.
Proof.
move=> g h Heq; apply/permP => x; apply: val_inj.
by rewrite -(ptbl_nth g) -(ptbl_nth h) Heq.
Qed.
Local Lemma ptbl_gen (i0 : 'I_3) : ptbl (tnth pgl27_gens i0) = mtbl (val i0).*2.
Proof.
by case: i0 => -[|[|[|//]]] Hi0';
  [exact: ptbl_gen0 | exact: ptbl_gen1 | exact: ptbl_gen2].
Qed.

(* Every one-letter successor of a key-table is a key. *)
Local Lemma keys_closed_mem (t : seq nat) (j : nat) :
  t \in unzip1 elem_table -> j \in [:: 0; 1; 2; 3; 4] ->
  mcomp t (mtbl j) \in unzip1 elem_table.
Proof. by move=> /mapP[sw Hsw ->] Hj; exact: elem_closed_mem. Qed.
Local Lemma double_lt3_mem (i0 : 'I_3) : (val i0).*2 \in [:: 0; 1; 2; 3; 4].
Proof. by move: i0 => [[|[|[|m]]] Hm]. Qed.
(* Composing a key with the table of a generator gives a key. *)
Local Lemma gen_key_mem (h : {perm 'I_8}) (t : seq nat) :
  h \in [set tnth pgl27_gens i0 | i0 : 'I_3] ->
  t \in unzip1 elem_table ->
  mcomp t (ptbl h) \in unzip1 elem_table.
Proof.
move=> /imsetP[i0 _ ->] Ht; rewrite ptbl_gen.
exact: (keys_closed_mem Ht (double_lt3_mem i0)).
Qed.

(* Every group element has its table among the closure keys: a group element
   is a product of generators, and the keys are closed under the generators
   and contain the identity.  The keys therefore cover the group. *)
Local Lemma group_key (g : {perm 'I_8}) :
  g \in pgg_G pgl27_M -> ptbl g \in unzip1 elem_table.
Proof.
suff key : forall (n : nat) (c : 'I_n -> {perm 'I_8}),
    (forall i, c i \in [set tnth pgl27_gens i0 | i0 : 'I_3]) ->
    ptbl (\prod_(i < n) c i)%g \in unzip1 elem_table.
  by move=> /gen_prodgP[n [c Hc ->]]; apply: key.
elim=> [|n IH] c Hc.
  by rewrite big_ord0 ptbl_id idt_in_keys.
rewrite big_ord_recr ptbl_morph.
have HP : ptbl (\prod_(i < n) c (widen_ord (leqnSn n) i))%g \in unzip1 elem_table.
  by apply: IH => i; exact: Hc.
exact: (gen_key_mem (Hc ord_max) HP).
Qed.

(* -------------------------------------------------------------------------- *)
(* The reverse direction: each key is the table of a word permutation.        *)
(* -------------------------------------------------------------------------- *)

Local Lemma gen_in_G (i : 'I_3) : tnth pgl27_gens i \in pgg_G pgl27_M.
Proof. by apply: mem_gen; apply/imsetP; exists i. Qed.

(* The perm-level letter selected by a nat index. *)
Local Definition gen5_of (j : nat) : {perm 'I_8} := tnth pgl27_sym_sigmas (inord j).
(* Every letter of the symmetrized alphabet lies in the shuffle group, the
   two inverse letters because a group is closed under inversion.  So
   symmetrizing the alphabet does not enlarge the state space. *)
Local Lemma gen5_of_mem (j : nat) : gen5_of j \in pgg_G pgl27_M.
Proof.
rewrite /gen5_of; move: (inord j : 'I_5) => [[|[|[|[|[|m]]]]] Hm] //;
  rewrite (tnth_nth 1%g) /=.
- exact: (gen_in_G (@Ordinal 3 0 isT)).
- by rewrite groupV; exact: (gen_in_G (@Ordinal 3 0 isT)).
- exact: (gen_in_G (@Ordinal 3 1 isT)).
- by rewrite groupV; exact: (gen_in_G (@Ordinal 3 1 isT)).
- exact: (gen_in_G (@Ordinal 3 2 isT)).
Qed.

(* A letter word folded into the composite shuffle permutation. *)
Local Definition word5_perm (w : seq nat) : {perm 'I_8} :=
  foldl (fun g j => (g * gen5_of j)%g) 1%g w.
Local Lemma word5_perm_mem (w : seq nat) : word5_perm w \in pgg_G pgl27_M.
Proof.
rewrite /word5_perm.
have g1 : (1%g : {perm 'I_8}) \in pgg_G pgl27_M by exact: group1.
elim: w (1%g) g1 => [|j w IH] g gG //=.
by apply: IH; apply: groupM => //; exact: gen5_of_mem.
Qed.
(* The table of the permutation of a letter word is the fold of the letters'
   tables from the identity table.  The BFS's fold over words and the group's
   product over letters are the same object, read through ptbl. *)
Local Lemma ptbl_word5 (w : seq nat) :
  all (fun j => j < 5) w ->
  ptbl (word5_perm w) = foldl (fun t j => mcomp t (mtbl j)) idt w.
Proof.
rewrite /word5_perm.
have gen : forall (w' : seq nat) (g : {perm 'I_8}),
    all (fun j => j < 5) w' ->
    ptbl (foldl (fun h j => (h * gen5_of j)%g) g w') =
    foldl (fun t j => mcomp t (mtbl j)) (ptbl g) w'.
  elim=> [|j w' IH] g //= /andP[Hj Hall].
  rewrite IH //; congr (foldl _ _ _).
  rewrite ptbl_morph; congr (mcomp _ _).
  rewrite /gen5_of ptbl_sym; congr mtbl; exact: (inordK Hj).
by move=> Hw; rewrite (gen w 1%g Hw) ptbl_id.
Qed.

(* The word permutation whose table is the k-th key. *)
Local Definition entry_perm (k : nat) : {perm 'I_8} :=
  word5_perm (nth ([::], [::]) elem_table k).2.
Local Lemma entry_perm_mem (k : nat) : entry_perm k \in pgg_G pgl27_M.
Proof. exact: word5_perm_mem. Qed.
(* The table of entry_perm k is the k-th key.  entry_perm is thus a section of
   the key indexing: every state index the walk uses names an actual shuffle,
   which is the direction group_key does not give. *)
Local Lemma ptbl_entry (k : nat) : k < 336 ->
  ptbl (entry_perm k) = nth [::] (unzip1 elem_table) k.
Proof.
move=> Hk.
have Hin : nth ([::], [::]) elem_table k \in elem_table
  by apply: mem_nth; rewrite size_elem_table.
rewrite /entry_perm (ptbl_word5 (elem_letters Hin)) (elem_fold_key Hin).
by rewrite /unzip1 (nth_map ([::], [::])) ?size_elem_table.
Qed.

(* -------------------------------------------------------------------------- *)
(* The group is exactly the 336 word permutations, counted by their keys.     *)
(* -------------------------------------------------------------------------- *)

Local Lemma keys_size : size (unzip1 elem_table) = 336.
Proof. by rewrite /unzip1 size_map size_elem_table. Qed.
(* Every group element is entry_perm k for some index k below 336.  With
   entry_perm_inj this makes k |-> entry_perm k a bijection from the 336 walk
   states onto the shuffle group. *)
Local Lemma mem_G_Ps (g : {perm 'I_8}) :
  g \in pgg_G pgl27_M -> g \in [seq entry_perm k | k <- iota 0 336].
Proof.
move=> Hg.
have Hk := group_key Hg.
set k := index (ptbl g) (unzip1 elem_table).
have Hklt : k < 336 by rewrite /k -keys_size index_mem.
have Hkey : ptbl (entry_perm k) = ptbl g.
  rewrite (ptbl_entry Hklt).
  exact: (@nth_index _ [::] (ptbl g) (unzip1 elem_table) Hk).
have Hgk : g = entry_perm k by apply: ptbl_inj; rewrite Hkey.
rewrite Hgk; apply: map_f; by rewrite mem_iota /= Hklt.
Qed.
(* Distinct indices below 336 name distinct shuffles, because their keys are
   distinct. *)
Local Lemma entry_perm_inj : {in iota 0 336 &, injective entry_perm}.
Proof.
move=> k1 k2; rewrite !mem_iota /= => Hk1 Hk2 Heq.
have Hs1 : k1 < size (unzip1 elem_table) by rewrite keys_size.
have Hs2 : k2 < size (unzip1 elem_table) by rewrite keys_size.
apply/eqP.
rewrite -(nth_uniq [::] Hs1 Hs2 uniq_elem_keys).
by apply/eqP; rewrite -(ptbl_entry Hk1) -(ptbl_entry Hk2) Heq.
Qed.

(** pgl27_gen5_eq — the symmetrized five-letter alphabet generates the same
    group as the three PGL(2,7) generators.  The realistic word shuffle
    therefore explores exactly the PGL(2,7) shuffle group, neither a subgroup
    nor a larger one, so uniformity on that group is the right mixing
    target. *)
Lemma pgl27_gen5_eq :
  <<[set tnth pgl27_sym_sigmas j | j : 'I_5]>>%G = pgg_G pgl27_M.
Proof.
apply: group_inj => /=; apply/eqP; rewrite eqEsubset; apply/andP; split.
- rewrite gen_subG; apply/subsetP => x /imsetP[j _ ->].
  by move: (gen5_of_mem (val j)); rewrite /gen5_of inord_val.
- rewrite gen_subG; apply/subsetP => x /imsetP[i _ ->].
  apply: mem_gen; apply/imsetP.
  move: i => [[|[|[|//]]] Hi'].
  + by exists (@Ordinal 5 0 isT).
  + by exists (@Ordinal 5 2 isT).
  + by exists (@Ordinal 5 4 isT).
Qed.

(** pgl27_card — the PGL(2,7) shuffle group has exactly 336 elements. The
    in-kernel order of the generated group, tying the walk's 336-entry state
    space to the whole group. *)
Lemma pgl27_card : #|pgg_G pgl27_M| = 336.
Proof.
have Hii : pgg_G pgl27_M =i [seq entry_perm k | k <- iota 0 336].
  move=> g; apply/idP/idP; first exact: mem_G_Ps.
  by move=> /mapP[k _ ->]; exact: entry_perm_mem.
rewrite (eq_card Hii).
have Huniq : uniq [seq entry_perm k | k <- iota 0 336].
  by rewrite map_inj_in_uniq; [exact: iota_uniq | exact: entry_perm_inj].
move/card_uniqP: Huniq => ->.
by rewrite size_map size_iota.
Qed.


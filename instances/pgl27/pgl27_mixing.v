(* pgl27_mixing: the binary-N random-walk ground layer of the PGL(2,7)        *)
(*               shuffle and the in-kernel order of the generated group       *)
(*                                                                            *)
(* The realistic word shuffle draws letters from the five symmetrized         *)
(* generators (translation, scaling, inversion and the two inverses). Its     *)
(* state space is the group generated by the three PGL(2,7) generators. A     *)
(* nat-level breadth-first search enumerates the group as permutation tables  *)
(* of 'I_8; a checker re-verifies the 336-entry closure. A companion binary-N *)
(* walk of length L = 200 tabulates the distribution reached from the         *)
(* identity, and a scalar checker certifies its total-variation bound.        *)
(*                                                                            *)
(* Definitions:                                                               *)
(*   pgl27_sym_sigmas == the inverse-closed five-letter generator tuple       *)
(*   mtbl j           == the permutation table of the j-th letter             *)
(*   elem_table       == the BFS closure, keys paired with carrying words     *)
(*   walkN L          == the length-L walk distribution over the 336 states   *)
(*                                                                            *)
(* Key results:                                                               *)
(*   elem_table_okT   == the closure has 336 uniq keys, closed under letters  *)
(*   mixing_bound_okT == the length-200 walk meets the 2^-40 mixing bound     *)
(*   pgl27_gen5_eq    == the five letters generate the PGL(2,7) group         *)
(*   pgl27_card       == the PGL(2,7) shuffle group has exactly 336 elements  *)
(*   pgl27_word_mixing     == the 200-letter word law is within 2^-40 of the  *)
(*                            uniform shuffle in variation distance           *)
(*   pgl27_endpoint_mixing == the same for each single-card marginal          *)
(*   pgl27_joint_mixing    == the same for the joint secret-and-shuffle law   *)
(*                                                                            *)
(******************************************************************************)

